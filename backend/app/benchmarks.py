"""Industry and sector peer distributions used for relative scoring.

`app/data/benchmarks.json` is generated by `scripts/build_benchmarks.py` from
real Yahoo Finance data (a GitHub Action refreshes it). Each group holds, per
metric, quantiles of that metric across the group's companies.
"""

from __future__ import annotations

import json
import re
from bisect import bisect_left
from dataclasses import dataclass
from functools import lru_cache
from pathlib import Path

DEFAULT_PATH = Path(__file__).parent / "data" / "benchmarks.json"
# An industry needs at least this many companies with data for a metric to be
# used as that metric's peer group; otherwise the wider sector is used.
MIN_PEERS = 8
QUANTILES = (0.05, 0.1, 0.25, 0.5, 0.75, 0.9, 0.95)


def norm(name: str | None) -> str:
    """'Software—Infrastructure' and 'Software - Infrastructure' -> 'softwareinfrastructure'."""
    return re.sub(r"[^a-z0-9]", "", (name or "").lower())


@dataclass(frozen=True)
class Distribution:
    count: int
    points: tuple[tuple[float, float], ...]  # (quantile, value), quantile ascending

    @property
    def median(self) -> float:
        return dict(self.points)[0.5]

    def percentile(self, value: float) -> float:
        """Approximate share of peers with a lower value (0..1)."""
        qs = [q for q, _ in self.points]
        vs = [v for _, v in self.points]
        if value < vs[0]:
            return qs[0] / 2
        if value > vs[-1]:
            return 1 - (1 - qs[-1]) / 2
        i = bisect_left(vs, value)
        if vs[i] == value:
            # On a quantile; if several quantiles share this value, rank in the middle of them.
            tied = [q for q, v in zip(qs, vs) if v == value]
            return (tied[0] + tied[-1]) / 2
        # vs[i-1] < value < vs[i]
        lo_v, hi_v, lo_q, hi_q = vs[i - 1], vs[i], qs[i - 1], qs[i]
        return lo_q + (hi_q - lo_q) * (value - lo_v) / (hi_v - lo_v)


@dataclass(frozen=True)
class PeerGroup:
    name: str
    level: str  # "industry" or "sector"
    companies: int
    metrics: dict[str, Distribution]


@dataclass(frozen=True)
class Benchmarks:
    groups: dict[str, PeerGroup]
    generated_at: str | None = None

    def lookup(self, industry: str | None, sector: str | None) -> tuple[PeerGroup | None, PeerGroup | None]:
        return self.groups.get("industry:" + norm(industry)), self.groups.get("sector:" + norm(sector))

    def for_metric(self, key: str, industry: PeerGroup | None, sector: PeerGroup | None
                   ) -> tuple[PeerGroup, Distribution] | None:
        for group in (industry, sector):
            if group and key in group.metrics and group.metrics[key].count >= MIN_PEERS:
                return group, group.metrics[key]
        return None


EMPTY = Benchmarks(groups={})


def parse(data: dict) -> Benchmarks:
    groups = {}
    for gid, g in data.get("groups", {}).items():
        metrics = {
            k: Distribution(count=int(m["count"]), points=tuple((float(q), float(v)) for q, v in m["q"]))
            for k, m in g.get("metrics", {}).items()
        }
        groups[gid] = PeerGroup(name=g["name"], level=g["level"], companies=int(g["companies"]), metrics=metrics)
    return Benchmarks(groups=groups, generated_at=data.get("generated_at"))


@lru_cache(maxsize=4)
def load(path: str = str(DEFAULT_PATH)) -> Benchmarks:
    p = Path(path)
    if not p.is_file():
        return EMPTY
    return parse(json.loads(p.read_text()))
